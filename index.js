/**
 * dsh-whale-sway — host half.
 *
 * The animation itself is client-side. This half exists for two reasons.
 *
 * ## 1. The bundle layer needs a row
 *
 * A package's `dsh.bundle` patch must insert a Loader entry for the package to
 * be instantiated, and the manifest's `dsh.client` declaration is only
 * discovered for a package the active profile has enabled. So this module is
 * the row: it owns no Host service, registers no tool, and holds no state.
 *
 * ## 2. The row's Config schema is what makes the plugin configurable
 *
 * DSH's settings domain projects a form out of a Loader entry's Config schema
 * (`@deepseek-ai/dsh-settings`: `describe()` → `volatileForm(schema)` → the
 * entry's editable fields) and persists every accepted edit into the profile
 * patch. The browser half then reads the same document through
 * `ctx.configForms.get('dsh-whale-sway')` and paints with it. So the schema
 * declared here *is* the configuration interface: each field is a parameter the
 * settings page exposes, its `.default()` is what the plugin runs with before
 * any override exists, and its bounds are what the Host validates a write
 * against.
 *
 * Every field is `.volatile()`: a volatile field is one the Loader can apply to
 * the running instance without a remount, and it is also the only kind
 * `volatileForm()` selects, so a non-volatile field would render nowhere.
 *
 * ## Why the schema package is resolved instead of imported
 *
 * A plugin installed with `link:` (or run from a checkout) resolves bare
 * specifiers from its own real path, which is outside any `node_modules` chain
 * that carries `@deepseek-ai/schemastery`; a static `import` would therefore
 * throw before this module ever exports anything, and the whole plugin would
 * fail to load rather than merely lose its settings page. The schema factory is
 * resolved at module load instead — from the running profile first, which is
 * where DSH keeps every package the composition can see — and the module
 * degrades to "no Config, no settings page" when resolution fails, leaving the
 * animation intact.
 *
 * The field table is not authored here: `tools/sync-settings.mjs` splices the
 * generated block below from `tools/settings.mjs`, the same table the browser
 * half and its tests read.
 */

