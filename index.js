// ---------------------------------------------------------------------
// Schema resolution
// ---------------------------------------------------------------------

/**
 * The paths a `require` is built from, in resolution order.
 *
 * The running profile comes first: DSH keeps the packages its composition can
 * see reachable from there, and the profile directory is exported to the
 * process as `DSH_PROFILE_DIR`. The bundled application root and the process
 * working directory follow, then this module's own directory — which is the one
 * that answers for a package installed normally, with its dependencies beside
 * it. Every candidate is cheap to try and a failure is silent here.
 *
 * @returns absolute paths, de-duplicated, in the order they are tried.
 */
function resolutionBases() {
  const bases = [];
  const push = (value) => {
    if (typeof value !== 'string' || value.length === 0) return;
    if (!bases.includes(value)) bases.push(value);
  };
  push(process.env.DSH_PROFILE_DIR);
  if (typeof process.env.DSH_HOME === 'string' && process.env.DSH_HOME.length > 0) {
    push(join(process.env.DSH_HOME, 'profiles'));
  }
  // The desktop host is launched as
  // `<app root>/dsh/node_modules/@deepseek-ai/dsh-desktop-host/lib/index.js <dsh root> <profile> …`,
  // so an argv entry that names the bundled application root is usable as a
  // resolution base even though the module itself lives outside it.
  const argv = Array.isArray(process.argv) ? process.argv : [];
  for (const entry of argv) {
    if (typeof entry !== 'string') continue;
    if (/[\\/]dsh[\\/]?$/.test(entry) || /app\.asar/.test(entry)) push(entry);
  }
  try {
    push(dirname(fileURLToPath(import.meta.url)));
  } catch (error) {
    /* an opaque module URL: the remaining bases still apply */
  }
  push(process.cwd());
  return bases;
}

/** Build a `require` rooted at one candidate: the entry itself when it is a file, else its directory. */
function requireFrom(entry) {
  const isFile = /\.(?:[cm]?js|json)$/i.test(entry);
  return createRequire(isFile ? entry : join(entry, 'package.json'));
}

/**
 * Resolve the schema factory, or `undefined` when no candidate carries it.
 *
 * @returns the schemastery factory — callable, with `.object()` — or undefined.
 */
function loadSchemaFactory() {
  for (const base of resolutionBases()) {
    let loaded;
    try {
      loaded = requireFrom(base)(SCHEMA_PACKAGE);
    } catch (error) {
      continue;
    }
    const factory = loaded !== null && typeof loaded === 'object' && loaded.default ? loaded.default : loaded;
    if (typeof factory === 'function' || (factory !== null && typeof factory === 'object' && typeof factory.object === 'function')) {
      return factory;
    }
  }
  return undefined;
}

/**
 * Build the Config schema from the generated field table.
 *
 * Each field becomes one schema node with its declared type, bounds, and
 * default, marked `.volatile()` so DSH can apply an edit to the live instance
 * without a remount — and so `volatileForm()` selects it for the settings page.
 *
 * @param factory - the schemastery factory.
 * @param fields - the generated field table.
 * @returns the object schema the Loader validates this row's config against.
 */
function buildConfigSchema(factory, fields) {
  const shape = {};
  for (const field of fields) {
    let node;
    if (field.type === 'enum') {
      node = factory.union([...field.values]);
    } else if (field.type === 'boolean') {
      node = factory.boolean();
    } else {
      node = factory.number();
      if (Number.isFinite(field.min)) node = node.min(field.min);
      if (Number.isFinite(field.max)) node = node.max(field.max);
      if (Number.isFinite(field.step)) node = node.step(field.step);
    }
    shape[field.id] = node.default(field.default).volatile();
  }
  return factory.object(shape);
}

const schemaFactory = loadSchemaFactory();

/**
 * The Loader entry's Config schema — the source of every parameter the settings
 * page exposes. It stays `undefined` (and DSH then serves no form for this
 * entry) when the schema package cannot be resolved, which is the documented
 * degradation rather than a load failure.
 */
const Config = schemaFactory === undefined ? undefined : buildConfigSchema(schemaFactory, SETTINGS_FIELDS);

/**
 * Nothing to set up and nothing to tear down.
 *
 * The one thing worth saying out loud is the degraded case: a composition whose
 * module resolution cannot reach `@deepseek-ai/schemastery` runs the plugin
 * without a settings page, and the reason should be visible in the log rather
 * than a silently missing UI.
 *
 * @param ctx - the Host plugin context.
 */
export function apply(ctx) {
  if (Config !== undefined) return;
  try {
    if (ctx !== null && ctx !== undefined && ctx.logger !== undefined && typeof ctx.logger.warn === 'function') {
      ctx.logger.warn(
        'no %s resolvable from the profile, so this plugin exposes no configurable fields; ' +
          'the animation is unaffected',
        SCHEMA_PACKAGE,
      );
    }
  } catch (error) {
    /* a context without a logger: the plugin still runs */
  }
}

export { Config };
