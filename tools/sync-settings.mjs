/**
 * Splice the generated settings literals into `index.js` and `client.js`.
 *
 * `tools/settings.mjs` declares every parameter the plugin exposes once. Two
 * halves of the package need that declaration as source-level literals:
 *
 *   - `index.js` builds the Loader entry's schemastery `Config` from it, which
 *     is what makes DSH project a settings form for the plugin at all;
 *   - `client.js` renders the controls from it (labels, hints, bounds, order)
 *     and normalizes whatever the Host accepted.
 *
 * Neither file may `import` the table: the Host half is loaded outside any
 * `node_modules` chain (see its header), and the browser half is a classic
 * script with no module system of its own. So the table is generated into both,
 * exactly as the sprite sheets are.
 *
 * This tool is the only writer of the region between the settings markers in
 * either file, it inserts that region when a file has none yet, and it is
 * idempotent: running it twice leaves the same bytes.
 *
 *   node tools/sync-settings.mjs          # splice (writes a file only when stale)
 *   node tools/sync-settings.mjs --check  # exit 1 when either file is out of date
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { SETTINGS_FIELDS, SETTINGS_GROUPS, settingsDictionary } from './settings.mjs';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const BEGIN = '/* dsh-whale-sway:settings:begin */';
const END = '/* dsh-whale-sway:settings:end */';

const check = process.argv.includes('--check');

/** Report one contract violation and stop, like every other tool in `tools/`. */
function fail(message) {
  console.error('[sync-settings] ' + message);
  process.exit(1);
}

/**
 * Both files are checked before either is written, so a run either updates the
 * whole contract or leaves the tree exactly as it found it.
 */
const targets = [
  {
    path: resolve(ROOT, 'index.js'),
    /** Where the block goes in a file that has none yet. */
    anchor: 'export const inject = [];',
    declaration: 'the Host half',
    names: ['SETTINGS_FIELDS'],
  },
  {
    path: resolve(ROOT, 'client.js'),
    anchor: '/* dsh-whale-sway:sheet:end */',
    declaration: 'the browser half',
    names: ['SETTINGS_FIELDS', 'SETTINGS_GROUPS', 'SETTINGS_I18N'],
  },
];

/** Pretty-print a generated value the way the source files carry it. */
function literal(value, indent) {
  const pad = ' '.repeat(indent);
  return JSON.stringify(value, null, 2).split('\n').join('\n' + pad);
}

/**
 * The values each file carries, by name. `index.js` needs the field table only;
 * `client.js` also renders groups and localized copy, so it carries the
 * dictionary the page registers.
 */
const dictionary = settingsDictionary();
const values = {
  SETTINGS_FIELDS,
  SETTINGS_GROUPS,
  SETTINGS_I18N: dictionary,
};

/**
 * Build one file's block.
 *
 * @param target - the file's contract: which literals it carries.
 * @param indent - the source indentation of the region in that file.
 * @returns the exact text between the markers, markers included.
 */
function buildBlock(target, indent) {
  const pad = ' '.repeat(indent);
  const lines = [
    BEGIN,
    pad + '// Generated by `node tools/sync-settings.mjs` from tools/settings.mjs.',
    pad + '// Do not edit by hand: this is the same parameter table the other half',
    pad + '// generates from, and `node tools/sync-settings.mjs --check` fails on drift.',
  ];
  for (const name of target.names) {
    lines.push(pad + 'var ' + name + ' = ' + literal(values[name], indent) + ';');
  }
  lines.push(pad + END);
  return lines.join('\n');
}

/**
 * Replace (or insert) one file's settings region.
 *
 * @param target - the file to splice, its anchor, and the literals it carries.
 * @returns the file's next text, and whether it differs from the current one.
 */
function splice(target) {
  const source = readFileSync(target.path, 'utf8');
  const begin = source.indexOf(BEGIN);
  const end = source.indexOf(END);
  const indent = target.path.endsWith('client.js') ? 2 : 0;
  const block = buildBlock(target, indent);

  if (begin < 0 && end < 0) {
    const anchor = source.indexOf(target.anchor);
    if (anchor < 0) fail(`${target.declaration} is missing both the settings markers and the insertion anchor`);
    const lineEnd = source.indexOf('\n', anchor);
    if (lineEnd < 0) fail(`${target.declaration} insertion anchor is the last line`);
    const next = source.slice(0, lineEnd + 1) + '\n' + block + '\n' + source.slice(lineEnd + 1);
    return { next, changed: true, inserted: true };
  }
  if (begin < 0 || end < 0 || end < begin) fail(`${target.declaration} has a damaged settings marker pair`);
  if (source.indexOf(BEGIN, begin + 1) >= 0 || source.indexOf(END, end + 1) >= 0) {
    fail(`${target.declaration} has duplicate settings markers`);
  }
  const next = source.slice(0, begin) + block + source.slice(end + END.length);
  return { next, changed: next !== source, inserted: false };
}

const results = targets.map((target) => ({ target, ...splice(target) }));

for (const result of results) {
  const { target, next, changed, inserted } = result;
  const name = target.path.slice(ROOT.length + 1);
  if (!changed) {
    console.log(`[sync-settings] ${name} is already in sync`);
    continue;
  }
  if (check) fail(`${name} is out of date — run \`node tools/sync-settings.mjs\``);
  writeFileSync(target.path, next);
  console.log(`[sync-settings] ${inserted ? 'inserted' : 'spliced'} the settings contract into ${name}`);
}

console.log(
  '[sync-settings] fields=' +
    SETTINGS_FIELDS.length +
    ' [' +
    SETTINGS_FIELDS.map((field) => field.id).join(' ') +
    '] groups=' +
    SETTINGS_GROUPS.length +
    ' strings=' +
    Object.keys(dictionary.zh).length +
    'x2',
);
